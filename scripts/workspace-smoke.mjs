import assert from 'node:assert/strict'
import { join } from 'node:path'

function shiftDate(date, days) {
  const value = new Date(`${date}T12:00:00Z`); value.setUTCDate(value.getUTCDate() + days)
  return value.toISOString().slice(0, 10)
}
export async function runWorkspaceChecks(context) {
  let page = context.page
  const { snapshot, waitUntil, runDirectory, databaseSQL } = context
  const checks = []
  const today = (await snapshot(page)).today.date, tomorrow = shiftDate(today, 1), yesterday = shiftDate(today, -1)
  const row = title => page.getByRole('article', { name: title, exact: true })
  const dialog = () => page.getByRole('dialog')
  const tab = name => page.getByRole('navigation', { name: '任务清单分类' }).getByRole('button', { name: new RegExp(`^${name}`) })
  async function selectDate(date) {
    if (!await page.getByLabel('查看日期', { exact: true }).isVisible()) await page.getByRole('button', { name: '日期与历史', exact: true }).click()
    await page.getByLabel('查看日期', { exact: true }).fill(date)
    await dialog().getByRole('button', { name: '查看', exact: true }).click()
    await dialog().waitFor({ state: 'hidden' })
    await waitUntil(async () => !await page.getByText('正在读取这一天…', { exact: true }).isVisible(), 'selected date rendered')
  }
  async function saveEditor() {
    await dialog().getByRole('button', { name: '保存安排', exact: true }).click()
    await dialog().waitFor({ state: 'hidden' })
  }
  async function newOnce(title, date = today) {
    await page.getByRole('button', { name: '定时或重复', exact: true }).click()
    await dialog().getByLabel('任务名称', { exact: true }).fill(title)
    await dialog().getByLabel('执行日期', { exact: true }).fill(date)
    await dialog().getByLabel('到点提醒', { exact: true }).uncheck()
    await saveEditor()
  }
  await page.getByRole('button', { name: '展开清单', exact: true }).click()
  // Setup only touches this run's isolated database; every feature below uses the actual UI.
  await page.evaluate(async () => {
    const result = await window.desktop.bootstrap()
    for (const item of result.value.today.items) if (item.kind === 'saved') await window.desktop.tasks.removeOccurrence(item.ref)
  })
  await page.getByLabel('新增待办', { exact: true }).fill('整理资料')
  await page.getByLabel('新增待办', { exact: true }).press('Enter')
  await row('整理资料').waitFor()
  const firstId = (await snapshot(page)).today.items.find(item => item.occurrence?.title === '整理资料').occurrence.id
  await row('整理资料').getByRole('button', { name: '编辑：整理资料', exact: true }).click()
  await dialog().getByLabel('任务名称', { exact: true }).fill('整理资料改')
  await dialog().getByLabel('执行日期', { exact: true }).fill(tomorrow)
  await dialog().getByLabel('提醒时间', { exact: true }).fill('10:30')
  await dialog().getByLabel('到点提醒', { exact: true }).uncheck()
  await page.screenshot({ path: join(runDirectory, 'once-editor.png'), omitBackground: true, animations: 'disabled' })
  await saveEditor()
  await row('整理资料改').waitFor()
  const future = await page.evaluate(date => window.desktop.tasks.getDay(date), tomorrow)
  assert.equal(future.value.items.find(item => item.kind === 'saved' && item.occurrence.title === '整理资料改').occurrence.id, firstId)
  assert.equal((await snapshot(page)).today.progress.total, 0)
  await row('整理资料改').getByRole('button', { name: '完成：整理资料改', exact: true }).click()
  await tab('已完成').click()
  await row('整理资料改').getByRole('button', { name: '撤销：整理资料改', exact: true }).click()
  await tab('待办').click()
  await row('整理资料改').waitFor()
  checks.push('UI quick create, edit date/time/reminder, future completion and undo preserve one occurrence ID and today progress')

  await selectDate(today)
  databaseSQL("CREATE TRIGGER m2_editor_failure BEFORE INSERT ON task_occurrences WHEN NEW.title='M2写入失败' BEGIN SELECT RAISE(ABORT,'editor storage failure'); END")
  await page.getByRole('button', { name: '定时或重复', exact: true }).click()
  await dialog().getByLabel('任务名称', { exact: true }).fill('M2写入失败')
  await dialog().getByRole('button', { name: '保存安排', exact: true }).click()
  await dialog().getByRole('alert').filter({ hasText: '本地数据读写失败' }).waitFor()
  assert.equal(await dialog().getByLabel('任务名称', { exact: true }).inputValue(), 'M2写入失败')
  assert.equal((await snapshot(page)).today.items.length, 0)
  databaseSQL('DROP TRIGGER m2_editor_failure')
  await saveEditor()
  await row('M2写入失败').waitFor()
  const editable = (await snapshot(page)).today.items.find(item => item.occurrence?.title === 'M2写入失败').occurrence
  await row('M2写入失败').getByRole('button', { name: '编辑：M2写入失败', exact: true }).click()
  await dialog().getByLabel('任务名称', { exact: true }).fill('我的未保存草稿')
  const external = await page.evaluate(item => window.desktop.tasks.updateOnce({ id: item.id, expectedVersion: item.version, title: '另一处已更新',
    scheduledDate: item.scheduledDate, scheduledTime: item.scheduledTime, reminderEnabled: item.reminderEnabled, scene: item.scene }), editable)
  assert.equal(external.ok, true)
  await dialog().getByRole('button', { name: '保存安排', exact: true }).click()
  await dialog().getByRole('alert').filter({ hasText: '记录已变化' }).waitFor()
  assert.equal(await dialog().getByLabel('任务名称', { exact: true }).inputValue(), '我的未保存草稿')
  await page.screenshot({ path: join(runDirectory, 'edit-conflict.png'), omitBackground: true, animations: 'disabled' })
  await dialog().getByRole('button', { name: '重新载入最新记录', exact: true }).click()
  await waitUntil(async () => await dialog().getByLabel('任务名称', { exact: true }).inputValue() === '另一处已更新', 'latest editor version loaded')
  await dialog().getByLabel('任务名称', { exact: true }).fill('重载后保存')
  await saveEditor()
  await row('重载后保存').waitFor()
  checks.push('UI editor keeps draft on real storage failure and version conflict; explicit reload permits a fresh edit')

  await page.getByRole('button', { name: '定时或重复', exact: true }).click()
  await dialog().getByRole('button', { name: '周期重复计划', exact: true }).click()
  await dialog().getByLabel('任务名称', { exact: true }).fill('每日拉伸')
  await dialog().getByLabel('开始日期', { exact: true }).fill(tomorrow)
  await dialog().getByLabel('结束日期', { exact: true }).fill(shiftDate(today, 2))
  await dialog().getByLabel('到点提醒', { exact: true }).uncheck()
  await dialog().getByRole('button', { name: '移除时间 15:00', exact: true }).click()
  await dialog().getByRole('button', { name: '＋ 添加时间', exact: true }).click()
  await dialog().getByRole('button', { name: '＋ 添加时间', exact: true }).click()
  await dialog().getByRole('alert').filter({ hasText: '已经存在' }).waitFor()
  await page.screenshot({ path: join(runDirectory, 'repeat-editor.png'), omitBackground: true, animations: 'disabled' })
  await saveEditor()
  await waitUntil(async () => await row('每日拉伸').count() === 2, 'two daily previews')
  const before = await page.evaluate(date => window.desktop.tasks.getDay(date), tomorrow)
  assert.equal(before.value.activated, false)
  const preview = before.value.items.find(item => item.kind === 'preview' && item.scheduledTime === '10:00')
  const planId = preview.ref.planId, slotId = preview.ref.slotId
  const previewRow = page.getByRole('article', { name: '每日拉伸', exact: true }).filter({ hasText: '10:00' })
  await previewRow.getByRole('button', { name: '完成：每日拉伸', exact: true }).click()
  await tab('已完成').click()
  await row('每日拉伸').getByRole('button', { name: '撤销：每日拉伸', exact: true }).click()
  await tab('待办').click()
  const materialized = await page.evaluate(date => window.desktop.tasks.getDay(date), tomorrow)
  const instanceId = materialized.value.items.find(item => item.kind === 'saved' && item.occurrence.slotId === slotId).occurrence.id
  await page.getByRole('article', { name: '每日拉伸', exact: true }).filter({ hasText: '10:00' }).getByRole('button', { name: '编辑：每日拉伸', exact: true }).click()
  await dialog().getByLabel('任务名称', { exact: true }).fill('每日拉伸新版')
  await dialog().getByLabel('时间槽 10:00', { exact: true }).fill('11:00')
  await saveEditor()
  await row('每日拉伸新版').getByRole('button', { name: '暂停', exact: true }).waitFor()
  const plans = await page.evaluate(() => window.desktop.plans.list())
  assert.equal(plans.value.find(plan => plan.id === planId).slots.find(slot => slot.id === slotId).localTime, '11:00')
  const editedDay = await page.evaluate(date => window.desktop.tasks.getDay(date), tomorrow)
  assert.equal(editedDay.value.items.find(item => item.kind === 'saved' && item.occurrence.id === instanceId).occurrence.scheduledTime, '11:00')
  await page.screenshot({ path: join(runDirectory, 'repeat-plans.png'), omitBackground: true, animations: 'disabled' })
  await row('每日拉伸新版').getByRole('button', { name: '暂停', exact: true }).click()
  await row('每日拉伸新版').getByText('已暂停', { exact: true }).waitFor()
  const paused = await page.evaluate(date => window.desktop.tasks.getDay(date), tomorrow)
  assert.equal(paused.value.items.filter(item => item.kind === 'preview' || item.occurrence.planId === planId).length, 0)
  await row('每日拉伸新版').getByRole('button', { name: '恢复', exact: true }).click()
  await row('每日拉伸新版').getByText('生效中', { exact: true }).waitFor()
  const resumed = await page.evaluate(date => window.desktop.tasks.getDay(date), tomorrow)
  assert.equal(resumed.value.items.find(item => item.kind === 'saved' && item.occurrence.slotId === slotId).occurrence.id, instanceId)
  await tab('待办').click()
  await page.getByRole('article', { name: '每日拉伸新版', exact: true }).filter({ hasText: '11:00' }).getByRole('button', { name: '完成：每日拉伸新版', exact: true }).click()
  await tab('周期计划').click()
  await row('每日拉伸新版').getByRole('button', { name: '结束', exact: true }).click()
  await dialog().getByRole('button', { name: '取消', exact: true }).click()
  await row('每日拉伸新版').getByRole('button', { name: '结束', exact: true }).click()
  await dialog().getByRole('button', { name: '确认结束', exact: true }).click()
  await dialog().waitFor({ state: 'hidden' })
  assert.equal(await row('每日拉伸新版').count(), 0)
  await tab('已完成').click()
  await row('每日拉伸新版').waitFor()
  await tab('待办').click()
  await row('每日拉伸新版').waitFor({ state: 'hidden' })
  assert.equal(await row('每日拉伸新版').count(), 0)
  await row('整理资料改').getByRole('button', { name: '删除本次：整理资料改', exact: true }).click()
  await row('整理资料改').waitFor({ state: 'hidden' })
  checks.push('UI daily plans add/remove/deduplicate slots, edit stable IDs, pause/resume, cancel ending and end while preserving completed history')

  const old = await page.evaluate(date => window.desktop.tasks.createOnce({ requestId: crypto.randomUUID(), title: '昨日未完成',
    scheduledDate: date, scheduledTime: null, reminderEnabled: false }), yesterday)
  assert.equal(old.ok, true)
  await selectDate(yesterday)
  await row('昨日未完成').waitFor()
  await page.screenshot({ path: join(runDirectory, 'history.png'), omitBackground: true, animations: 'disabled' })
  const todayBeforeMove = (await snapshot(page)).today.progress
  await page.getByRole('button', { name: '仅显示桌宠', exact: true }).click()
  const dock = page.getByRole('button', { name: '展开清单', exact: true })
  assert.ok((await dock.textContent()).includes(`今天 ${todayBeforeMove.completed}/${todayBeforeMove.total}`))
  await dock.click()
  await row('昨日未完成').getByRole('button', { name: '移到今天', exact: true }).click()
  await row('昨日未完成').waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '返回今天', exact: true }).click()
  await row('昨日未完成').getByText(`原 ${yesterday.slice(5)}`, { exact: true }).waitFor()
  const moved = (await snapshot(page)).today.items.find(item => item.occurrence?.id === old.value.id).occurrence
  assert.equal(moved.sourceDate, yesterday)
  const totalAfterMove = (await snapshot(page)).today.progress.total
  await page.evaluate(id => window.desktop.tasks.moveToToday({ id }), old.value.id)
  assert.equal((await snapshot(page)).today.progress.total, totalAfterMove)
  await selectDate(shiftDate(today, -10))
  await page.getByText('没有生成记录', { exact: true }).waitFor()
  for (const name of ['明天', '昨天', '明天']) {
    await page.getByRole('button', { name: '日期与历史', exact: true }).click()
    await page.getByRole('button', { name, exact: true }).click()
    await dialog().waitFor({ state: 'hidden' })
  }
  await tab('待办').click()
  assert.equal(await row('整理资料改').count(), 0)
  await tab('已完成').click()
  await row('每日拉伸新版').waitFor()
  checks.push('UI history migration keeps source date and ID; unrun days show no generated record; date changes and compact mode retain today statistics')

  await page.getByRole('button', { name: '返回今天', exact: true }).click()
  await tab('待办').click()
  const daily = await page.evaluate(date => window.desktop.plans.create({ requestId: crypto.randomUUID(), title: '跨天生成', startDate: date,
    endDate: null, times: ['10:00', '15:00'], reminderEnabled: false }), today)
  assert.equal(daily.ok, true)
  await waitUntil(async () => await row('跨天生成').count() === 2, 'today recurring occurrences')
  await row('跨天生成').filter({ hasText: '10:00' }).getByRole('button', { name: '完成：跨天生成', exact: true }).click()
  const nextNoon = await page.evaluate(date => new Date(`${date}T12:00:00`).getTime(), tomorrow)
  await context.withMainClock(nextNoon, async () => {
    const next = await snapshot(page)
    assert.equal(next.today.date, tomorrow)
    const newItems = next.today.items.filter(item => item.kind === 'saved' && item.occurrence.planId === daily.value.id)
    assert.equal(newItems.length, 2)
    assert.ok(newItems.every(item => item.occurrence.status === 'pending'))
    const oldDay = await page.evaluate(date => window.desktop.tasks.getDay(date), today)
    const oldItems = oldDay.value.items.filter(item => item.kind === 'saved' && item.occurrence.planId === daily.value.id)
    assert.equal(oldItems.filter(item => item.occurrence.status === 'pending').length, 1)
    assert.equal(oldItems.filter(item => item.occurrence.status === 'completed').length, 1)
    await waitUntil(async () => (await page.locator('.progress-caption').textContent()).includes(`待办进度 ${next.today.progress.completed}/${next.today.progress.total}`), 'today view follows coordinated day')
    assert.equal(await page.getByRole('button', { name: '返回今天', exact: true }).count(), 0)
  })
  checks.push('controlled main clock crosses a day: UI follows today, creates two fresh instances and preserves yesterday completion and pending facts')

  page = await context.restart()
  if ((await snapshot(page)).window.mode === 'compact') await page.getByRole('button', { name: '展开清单', exact: true }).click()
  await row('昨日未完成').waitFor()
  assert.equal((await snapshot(page)).today.items.filter(item => item.occurrence?.id === old.value.id).length, 1)
  await selectDate(tomorrow)
  await tab('已完成').click()
  await row('每日拉伸新版').waitFor()
  await tab('周期计划').click()
  assert.equal(await row('每日拉伸新版').count(), 0)
  await tab('待办').click()
  assert.equal(await row('整理资料改').count(), 0)
  await page.getByRole('button', { name: '返回今天', exact: true }).click()
  await page.screenshot({ path: join(runDirectory, 'm2-final.png'), omitBackground: true, animations: 'disabled' })
  checks.push('M2 UI restart restores moved task once, completed plan history, ended state and deletion tombstones')
  return checks
}
